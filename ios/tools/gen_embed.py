#!/usr/bin/env python3
"""Generate the iOS embedded-module assembly and ios_embed.h for the MacNativeGames runtime.

Usage: gen_embed.py <runtime_tables.h> <rewritten dir> <export dir> <output dir>

The loader (runtime/loader.c, TARGET_OS_IPHONE) vm_remaps three parts of each module back to their original offsets:
text [0, page_up(text_end)) from __TOTKX/__<name>x0 (r-x), the data part [page_up(text_end), patch_off) from
__TOTK<name>W/__img (rw), and the patch area [patch_off, page_up(file_size)) from __TOTKX/__<name>x1 (r-x). The exported
text comes from `totk-native <rewritten> export-ios` (game patches applied); the data part and patch area come from the
verified rewritten image (the patch area is zero-padded to page_up(file_size), which is how the Mac loader maps it).
"""
import hashlib
import re
import sys
from pathlib import Path

PAGE = 0x4000
def page_up(n): return (n + PAGE - 1) & ~(PAGE - 1)

def modules_from_tables(path):
    text = path.read_text()
    rows = []
    for m in re.finditer(r'\{\.name="([^"]+)",\.digest="([0-9a-f]+)",\.file_size=(\d+)ULL,\.text_end=(\d+)ULL,'
                         r'\.ro_off=(\d+)ULL,\.data_off=(\d+)ULL,\.patch_off=(\d+)ULL,\.key_off=(\d+)ULL', text):
        rows.append(dict(name=m.group(1), file_size=int(m.group(3)), text_end=int(m.group(4)), patch_off=int(m.group(7))))
    if len(rows) != 3: raise SystemExit(f'expected 3 module rows in {path}, found {len(rows)}')
    return rows

def main():
    if len(sys.argv) != 5: raise SystemExit(__doc__)
    tables, rewritten, export, out = map(Path, sys.argv[1:5])
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    asm = ['// Generated by tools/gen_embed.py — do not edit']
    struct = []
    for m in modules_from_tables(tables):
        name = m['name']; n_text = page_up(m['text_end'])
        img = (rewritten / f'{name}.patched.bin').read_bytes()
        x0 = (export / f'{name}.x0.bin').read_bytes()
        if len(x0) != n_text: raise SystemExit(f'{name}: exported text {len(x0)} != page_up(text_end) {n_text}')
        w = img[n_text:m['patch_off']]
        # The live patch area after the game patches (real-time frame-step / output veneers) comes from export-ios when
        # available; the plain rewritten image cannot contain it because it lives past file_size.
        n_patch = page_up(m['file_size']) - m['patch_off']
        x1_export = export / f'{name}.x1.bin'
        x1 = x1_export.read_bytes() if x1_export.exists() else img[m['patch_off']:].ljust(n_patch, b'\0')
        if len(x1) != n_patch: raise SystemExit(f'{name}: patch area export {len(x1)} != {n_patch}')
        if not (w and x1): raise SystemExit(f'{name}: empty part')
        # Write the parts next to the assembly so .incbin paths stay short and stable.
        for part, data in (('x0', x0), ('w', w), ('x1', x1)):
            (out / f'{name}.{part}.bin').write_bytes(data)
        asm += [f'    .section __TOTKX,__{name}x0', '    .p2align 14', f'    .incbin "{out}/{name}.x0.bin"',
                f'    .section __TOTK{name}W,__img', '    .p2align 14', f'    .incbin "{out}/{name}.w.bin"',
                f'    .section __TOTKX,__{name}x1', '    .p2align 14', f'    .incbin "{out}/{name}.x1.bin"']
        struct.append((name, hashlib.sha256(x0).hexdigest(), hashlib.sha256(w).hexdigest(), hashlib.sha256(x1).hexdigest()))
        print(f'{name}: text {len(x0)} data {len(w)} patch {len(x1)}')
    (out / 'embed.S').write_text('\n'.join(asm) + '\n')
    rows = ''.join(f' {{"{n}", "{a}", "{b}", "{c}"}},\n' for n, a, b, c in struct)
    (out / 'ios_embed.h').write_text('#pragma once\ntypedef struct { const char *name, *x0, *w, *x1; } IosEmbed;\n'
                                     'static const IosEmbed ios_embed[] = {\n' + rows + '};\n')
    print('wrote', out / 'embed.S', 'and', out / 'ios_embed.h')

if __name__ == '__main__': main()
